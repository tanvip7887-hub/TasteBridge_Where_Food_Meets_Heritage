import { AppError } from "../../utils/AppError.js";
import { HTTP_STATUS } from "../../constants/index.js";
import { createNotificationsService } from "../notifications/notifications.service.js";

const notFound = (message = "Booking not found.") => new AppError(message, HTTP_STATUS.NOT_FOUND);
const conflict = (message) => new AppError(message, HTTP_STATUS.CONFLICT);
const REVIEW_WINDOW_MS = 14 * 24 * 60 * 60 * 1000;
const isReviewWindowOpen = (completedAt, currentTime) => {
  const completionTime = new Date(completedAt).getTime();
  const currentTimeMs = currentTime.getTime();
  return Number.isFinite(completionTime)
    && completionTime <= currentTimeMs
    && currentTimeMs <= completionTime + REVIEW_WINDOW_MS;
};
const missingCompletionTimestamp = () => new AppError(
  "This booking is marked completed but has no authoritative completion timestamp, so completion cannot be verified.",
  HTTP_STATUS.SERVICE_UNAVAILABLE,
);
const bookingInclude = {
  experience: { select: { id: true, cookId: true, title: true, location: true, durationMinutes: true } },
  customer: { select: { id: true, name: true } },
  slot: { select: { startsAt: true, endsAt: true } },
};
const bookingListInclude = {
  experience: { select: { id: true, cookId: true, type: true, title: true, location: true, durationMinutes: true } },
  customer: { select: { id: true, name: true } },
  slot: { select: { startsAt: true, endsAt: true } },
  paymentAttempts: {
    orderBy: { createdAt: "desc" },
    take: 1,
    select: {
      attemptNumber: true,
      provider: true,
      amount: true,
      currency: true,
      status: true,
      verificationMode: true,
      succeededAt: true,
      refund: { select: { amount: true, currency: true, status: true, provider: true, verificationMode: true, succeededAt: true } },
    },
  },
};
const completionBookingInclude = {
  ...bookingInclude,
};

const notifyReviewRequested = async (tx, booking) => {
  await createNotificationsService(tx).create({
    userId: booking.customerId,
    portal: "CUSTOMER",
    type: "ORDER_ALERT",
    title: "Your event review is welcome",
    message: `${booking.experience.title} is complete. Share your review while the review window is open.`,
    metadata: { kind: "REVIEW_REQUESTED", reviewType: "EXPERIENCE", bookingId: booking.id, href: `/reviews?bookingId=${encodeURIComponent(booking.id)}` },
    eventKey: `experience-booking:${booking.id}:review-request:customer:${booking.customerId}`,
  });
};

export const createExperienceBookingsService = (database, { now = () => new Date() } = {}) => ({
  async listForCook(cookId, experienceType) {
    if (experienceType && !["HOME_DINING", "WORKSHOP"].includes(experienceType)) {
      throw new AppError("Unsupported experience booking type.", HTTP_STATUS.BAD_REQUEST);
    }
    const bookings = await database.experienceBooking.findMany({
      where: { experience: { cookId, ...(experienceType ? { type: experienceType } : {}) } },
      orderBy: [{ bookingDate: "desc" }, { id: "desc" }],
      include: bookingListInclude,
    });
    return { items: bookings };
  },

  /**
   * A cook explicitly confirms that their own confirmed event booking took place.
   * The authoritative completion timestamp is generated by the server at this action;
   * it is never inferred from bookingDate or updatedAt. The guarded write, status change,
   * and customer review-request notification commit atomically.
   */
  async completeBooking({ bookingId, cookId }) {
    if (!cookId) throw new AppError("An approved cook account is required.", HTTP_STATUS.FORBIDDEN);
    const completedAt = now();
    try {
      return await database.$transaction(async (tx) => {
        const booking = await tx.experienceBooking.findFirst({
          where: { id: bookingId, experience: { cookId } },
          include: completionBookingInclude,
        });
        if (!booking) throw notFound("Booking not found for this cook kitchen.");
        if (booking.status === "CANCELLED") throw conflict("Cancelled bookings cannot be completed.");
        if (booking.status === "COMPLETED") {
          if (!booking.completedAt) throw missingCompletionTimestamp();
          // Re-ensure the same event notification after a retry; its deterministic key
          // makes this safe if the original transaction committed.
          if (isReviewWindowOpen(booking.completedAt, completedAt)) await notifyReviewRequested(tx, booking);
          return booking;
        }
        if (booking.status !== "CONFIRMED") throw conflict("Only confirmed bookings can be completed.");

        // Dine slots have authoritative start/end instants. Older slotless
        // bookings retain only bookingDate, which is their persisted scheduled
        // start time; never infer a completion time from client input or updatedAt.
        const scheduledCompletionAt = booking.slotId ? booking.slot?.endsAt : booking.bookingDate;
        if (!(scheduledCompletionAt instanceof Date) || !Number.isFinite(scheduledCompletionAt.getTime())) {
          throw conflict("The scheduled experience end time is unavailable, so this booking cannot be completed yet.");
        }
        if (completedAt < scheduledCompletionAt) {
          throw conflict("A confirmed booking cannot be completed before its scheduled experience has ended.");
        }

        const updated = await tx.experienceBooking.updateMany({
          where: { id: bookingId, status: "CONFIRMED", completedAt: null, experience: { cookId } },
          data: { status: "COMPLETED", completedAt },
        });
        if (updated.count !== 1) throw conflict("The booking changed while it was being completed. Refresh and try again.");

        const completed = await tx.experienceBooking.findFirst({
          where: { id: bookingId, experience: { cookId }, status: "COMPLETED" },
          include: completionBookingInclude,
        });
        if (!completed?.completedAt) throw conflict("The completed booking could not be verified.");
        await notifyReviewRequested(tx, completed);
        return completed;
      }, { isolationLevel: "Serializable" });
    } catch (error) {
      if (error?.code === "P2034") {
        const current = await database.experienceBooking.findFirst({
          where: { id: bookingId, experience: { cookId }, status: "COMPLETED", completedAt: { not: null } },
          include: bookingInclude,
        });
        if (current) {
          if (!isReviewWindowOpen(current.completedAt, completedAt)) return current;
          await database.$transaction((tx) => notifyReviewRequested(tx, current));
          return current;
        }
        throw conflict("The booking changed while it was being completed. Refresh and try again.");
      }
      throw error;
    }
  },

  async updateBookingDetails({ bookingId, numberOfGuests }) {
    return database.$transaction(async (tx) => {
      const booking = await tx.experienceBooking.findUnique({ where: { id: bookingId } });
      if (!booking) throw notFound();
      return tx.experienceBooking.update({
        where: { id: bookingId },
        data: numberOfGuests === undefined ? {} : { numberOfGuests },
      });
    });
  },
});
